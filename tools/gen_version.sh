#!/bin/bash
# tools/gen_version.sh [OUT]: core/version.h (or OUT) from the VERSION file at the repo root (docs/versioning.md) - the
# version, the short git commit and a dirty flag. Rewritten only when its content changes, so a build that has not moved
# does not recompile what includes it. Run by every build (core/Makefile, pi/engine/build.sh, teensy/setup_core_lib.sh);
# the file is git-ignored. Tests: tools/tests/test_gen_version.sh (make -C pi/engine/tests).
# Dirty means the built tree is not the commit: a tracked file changed, or an untracked (not ignored) file sits in the
# build's inputs - the Makefiles glob core/*/*.cpp, so a new source file is in the kernel before it is committed - or
# the tree's state could not be read at all (git status failed: not known to be clean).
set -eo pipefail
R=$(cd "$(dirname "$0")/.." && pwd)
OUT=${1:-$R/core/version.h}
V=$(tr -d ' \t\r\n' < "$R/VERSION")
case "$V" in [0-9]*.[0-9]*.[0-9]*) ;; *) echo "VERSION: \"$V\" is not MAJOR.MINOR.PATCH" >&2; exit 1 ;; esac
C=$(git -C "$R" rev-parse --short=7 HEAD 2>/dev/null || echo unknown)
D=0
# the build's inputs, for untracked files: notes (*.md, docs/) and anything elsewhere are not compiled
INPUTS=(VERSION core pi/engine pi/ui ':(glob)pi/circle/*' teensy web sdk tools ':(exclude,glob)**/*.md')
if [ "$C" != unknown ]; then
  if ! T=$(git -C "$R" status --porcelain --untracked-files=no 2>/dev/null) \
     || ! U=$(git -C "$R" ls-files --others --exclude-standard -- "${INPUTS[@]}" 2>/dev/null); then
    D=1						# state unknown: never stamped clean
  elif [ -n "$T" ] || [ -n "$U" ]; then
    D=1
  fi
fi
F="$C"; [ "$D" = 1 ] && F="$C-dirty"
H=$(printf '// core/version.h - generated by tools/gen_version.sh from VERSION; do not edit, not in git.\n#pragma once\n#define SIDECAR_VERSION\t"%s"\n#define SIDECAR_COMMIT\t"%s"\n#define SIDECAR_DIRTY\t%s\n#define SIDECAR_VERSION_FULL\t"%s (%s)"\n' "$V" "$C" "$D" "$V" "$F")
[ "$(cat "$OUT" 2>/dev/null)" = "$H" ] || printf '%s\n' "$H" > "$OUT"
