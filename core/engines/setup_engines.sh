#!/bin/bash
# The Teensy's curated engine sources - libraries Plaits, Juno, DaisySP, Sampler as teensy/setup_*_lib.sh
# (and MDKit, from third_party/mdkit: the built-in MD; not the Teensy's)
# make them - copied for a non-Arduino build into DEST/<Lib>/, with the Teensy-only bits undone (PROGMEM and
# <avr/pgmspace.h> on Plaits' tables, the .flashmem section on Voice::Init; as pi/circle/spike3/setup_plaits.sh).
# The same sources the Teensy builds, so the Mac and the Pi play what the Teensy plays.
#   core/engines/setup_engines.sh DEST      (core/Makefile: core/build/engines; pi/engine/Makefile: its own)
# Git-ignored output; rerun freely. Runs the Teensy's setup scripts for a missing library.
set -euo pipefail
D=$(cd "$(dirname "$0")" && pwd)
T=$(cd "$D/../../teensy" && pwd)
DEST=${1:?usage: setup_engines.sh DEST}
# remade when missing, or when this repo's own files in it (sim/plaits/fm_machine.h, the user_data.h shim) changed
# (measured: a stale fm_machine.h failed test_content's fm)
"$T/setup_plaits_lib.sh" --if-stale >/dev/null
[ -d "$T/libraries/DaisySP" ] || "$T/setup_daisysp_lib.sh" >/dev/null
"$T/setup_juno_lib.sh" >/dev/null
"$T/setup_sampler_lib.sh" >/dev/null
rm -rf "$DEST"; mkdir -p "$DEST"
for lib in Plaits Juno DaisySP Sampler; do cp -R "$T/libraries/$lib/src" "$DEST/$lib"; done
# MDKit: the built-in MD (core/md/md.h, voice byte 0x40; Pi and Mac only): mdkit's 30 voices from the vendored copy
# (third_party/mdkit, no network) flat in MDKit/, the PI cymbals windowed as the MD plugin's (plugins/mdkit/patch_pi.py),
# and the MD plugin's own glue (plugins/mdkit/mdk.c, unchanged) compiled through MDKit/mdk_builtin.c with its entry
# renamed: one source for the plugin and the built-in.
R=$(cd "$D/../.." && pwd)
M="$DEST/MDKit"
mkdir -p "$M/glue/rmp"
cp "$R/third_party/mdkit/include/"*.h "$M/"
for f in "$R"/third_party/mdkit/src/*/*/mdkit_*.[ch]; do cp "$f" "$M/"; done
for v in rc cc hh; do python3 "$R/plugins/mdkit/patch_pi.py" "$R/third_party/mdkit/src/pi/$v" "$M" "$v" >/dev/null; done
cp "$R/plugins/mdkit/"{mdk.c,families.h,mdk_tap.h,mdk_fir.h,md_tables.h} "$M/glue/"
cp "$R/sdk/rmp/rmp_api.h" "$M/glue/rmp/"
cat > "$M/mdk_builtin.c" <<'C'
/* generated by core/engines/setup_engines.sh: the MD plugin's glue as the core's built-in MD (core/md/md.cpp) */
#define MDK_FAM_MD 1
#define MDK_BUILTIN 1
#define RMP_NATIVE 1
#define rmp_entry mdk_builtin_entry
#include "glue/mdk.c"
C
for f in "$DEST/Plaits/plaits/resources.cc" "$DEST/Plaits/plaits/dsp/speech/lpc_speech_synth_words.cc"; do
  sed -i '' -e '/^#include <avr\/pgmspace.h>$/d' -e 's/\] PROGMEM = {/] = {/' "$f"
done
sed -i '' 's|^__attribute__((section(".flashmem"))) void Voice::Init|void Voice::Init|' "$DEST/Plaits/plaits/dsp/voice.cc"
! grep -rqE 'PROGMEM|pgmspace|section\("\.flashmem"\)' "$DEST/Plaits" || { echo "setup_engines.sh: Teensy-only bits left in Plaits"; exit 1; }
echo "engines in $DEST ($(find "$DEST" -name '*.cc' -o -name '*.cpp' -o -name '*.c' | wc -l | tr -d ' ') sources)"
