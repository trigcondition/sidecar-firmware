#!/usr/bin/env python3
"""plugins/mdkit/gen_tables.py - md_tables.h from md.json and voices.json: the MD machine's ENGINE / TYPE names, its
per-TYPE knob labels and mdkit's per-TYPE control defaults, for the built-in MD engine (core/md/md.cpp, voice byte
0x40); and the defaults table in docs/MD-BUILTIN.md (between its md-defaults markers: the Rytm's conversion of stored
DIGIDRUM sounds needs them with no Sidecar connected). md.json (gen.py's output, the MD user
machine's manifest) stays the one source: the packer reads it for the plugin, this header carries the same words into
the core. The output is committed; run it again after gen.py.
MIT, Copyright 2026 trigcondition and contributors.

    python3 gen_tables.py
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))


def c(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


FAMILY = {"FM": "efm", "PI": "pi", "TRX": "trx"}   # MD's ENGINE names -> mdkit's families (voices.json keys)
DOC = os.path.join(HERE, "..", "..", "docs", "MD-BUILTIN.md")


def main():
    m = json.load(open(os.path.join(HERE, "md.json")))
    voices = json.load(open(os.path.join(HERE, "voices.json")))
    knobs = {k["p"]: k for k in m["knobs"]}
    tl = m["type_labels"]
    eng = knobs[tl["follows"]]["names"]
    lists = tl["lists"]
    sets = tl["sets"]
    assert len(eng) == len(lists) and sum(len(l) for l in lists) == len(sets) and tl["params"] == list(range(1, 9))
    o = ["// plugins/mdkit/md_tables.h - generated by gen_tables.py from md.json: do not edit.",
         "// MD's ENGINEs, each ENGINE's TYPEs, and per TYPE (over all ENGINEs, the order of families.h MDK_FAM_MD) the",
         "// long / short label of P1..P8 (\"\" for a control the TYPE lacks). MIT, Copyright 2026 trigcondition and contributors.",
         "#pragma once",
         f"#define MDT_ENGINES {len(eng)}",
         f"#define MDT_SETS {len(sets)}",
         "static const char *const mdt_engine_names[MDT_ENGINES] = {" + ", ".join(c(e) for e in eng) + "};",
         "static const unsigned char mdt_count[MDT_ENGINES] = {" + ", ".join(str(len(l)) for l in lists) + "};",
         "static const unsigned char mdt_base[MDT_ENGINES] = {" +
         ", ".join(str(sum(len(l) for l in lists[:i])) for i in range(len(lists))) + "};",
         "static const char *const mdt_type_names[MDT_SETS] = {" + ", ".join(c(n) for l in lists for n in l) + "};",
         "static const char *const mdt_label[MDT_SETS][8][2] = {"]
    for s in sets:
        o.append("    {" + ", ".join("{%s, %s}" % (c(e[0]), c(e[1])) if e else '{"", ""}' for e in s) + "},")
    o.append("};")
    defaults = []   # per set, 8 values: mdkit's control defaults, 0 for a control the TYPE lacks
    for e, names in zip(eng, lists):
        for n in names:
            c_ = [d for _, d in voices[f"{FAMILY[e]}_{n.lower()}"]["controls"]]
            defaults.append((c_ + [0] * 8)[:8])
    o.append("static const unsigned char mdt_default[MDT_SETS][8] = {")
    for d in defaults:
        o.append("    {" + ", ".join(str(x) for x in d) + "},")
    o.append("};")
    for p, name in ((tl["follows"], "ENGINE"), (tl["knob"], "TYPE")):
        o.append(f"#define MDT_P_{name} {p}")
    lv = knobs[11]
    o.append(f"#define MDT_P_LEVEL {lv['p']}")
    o.append(f"#define MDT_LEVEL_DEFAULT {lv['default']}")
    o.append("static const char *const mdt_knob_long[3] = {" + ", ".join(c(knobs[p]["long"]) for p in (9, 10, 11)) + "};")
    o.append("static const char *const mdt_knob_short[3] = {" + ", ".join(c(knobs[p]["short"]) for p in (9, 10, 11)) + "};")
    open(os.path.join(HERE, "md_tables.h"), "w").write("\n".join(o) + "\n")
    # the doc's table (set, ENGINE, TYPE, P1..P8 defaults; "-" a control the TYPE lacks)
    rows = ["| set | ENGINE | TYPE | P1 | P2 | P3 | P4 | P5 | P6 | P7 | P8 |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    s = 0
    for e, names in zip(eng, lists):
        for n in names:
            k = len(voices[f"{FAMILY[e]}_{n.lower()}"]["controls"])
            rows.append(f"| {s} | {e} | {n} | " + " | ".join(str(defaults[s][i]) if i < k else "-" for i in range(8)) + " |")
            s += 1
    b, x = "<!-- md-defaults begin (plugins/mdkit/gen_tables.py) -->", "<!-- md-defaults end -->"
    doc = open(DOC).read()
    i, j = doc.index(b), doc.index(x)
    open(DOC, "w").write(doc[:i + len(b)] + "\n" + "\n".join(rows) + "\n" + doc[j:])


if __name__ == "__main__":
    main()
