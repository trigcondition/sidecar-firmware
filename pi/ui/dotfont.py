def _strokes(r):
    return sum(1 for i in range(len(r)) if r[i] == '#' and (i + 1 < len(r) and r[i + 1] == '#'))


def stretch59(rows):
    def pick(cands):
        for i in cands:
            if rows[i] == rows[i - 1] or rows[i] == rows[i + 1]: return i
        return min(cands, key=lambda i: (_strokes(rows[i]), abs(i - cands[0])))
    a, b = pick([1, 2]), pick([4, 5])
    out = []
    for i, r in enumerate(rows):
        out.append(r)
        if i in (a, b): out.append(r)
    return out


F59 = {k: F59_ART.get(k, None) or stretch59(v) for k, v in F57.items()}


def pack(name, h, font):
    out = []
    for k in sorted(font, key=lambda c: ord(c) if isinstance(c, str) else c):
        rows = font[k]
        cp = ord(k) if isinstance(k, str) else k
        w = len(rows[0])
        assert len(rows) == h, (name, k, len(rows))
        assert all(len(r) == w for r in rows) and 1 <= w <= 8 and h <= 10, (name, k)
        bits = [sum(1 << (w - 1 - x) for x, c in enumerate(r) if c == '#') for r in rows]
        bits += [0] * (10 - h)
        out.append("\t{0x%04X, %d, {%s}},\t// %s" % (cp, w, ", ".join("0x%02X" % b for b in bits),
                                                    k if isinstance(k, str) and k.isprintable() and k not in "\\'" else "U+%04X" % cp))
    return out


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
    a, b, c, d = pack("5x7", 7, F57), pack("3x5", 5, F35), pack("4x6", 6, F46), pack("5x9", 9, F59)
    with open(os.path.join(out, "sidecar_dotfont.c"), "w") as f:
        f.write("// pi/ui/sidecar_dotfont.c - generated by pi/ui/dotfont.py (edit the ASCII art there, then run it): the OLED\n"
                "// theme's pixel fonts, designed for Sidecar (no third-party font). One byte a row, bit w-1 = the leftmost column.\n"
                "#include \"sidecar_dotfont.h\"\n\n")
        f.write("static const dotglyph_t k57[] = {\n%s\n};\n\n" % "\n".join(a))
        f.write("static const dotglyph_t k35[] = {\n%s\n};\n\n" % "\n".join(b))
        f.write("static const dotglyph_t k46[] = {\n%s\n};\n\n" % "\n".join(c))
        f.write("static const dotglyph_t k59[] = {\n%s\n};\n\n" % "\n".join(d))
        f.write("const dotfont_t dotfont_5x7 = {7, %d, k57};\n" % len(a))
        f.write("const dotfont_t dotfont_3x5 = {5, %d, k35};\n" % len(b))
        f.write("const dotfont_t dotfont_4x6 = {6, %d, k46};\n" % len(c))
        f.write("const dotfont_t dotfont_5x9 = {9, %d, k59};\n" % len(d))
    print("sidecar_dotfont.c: %d + %d + %d + %d glyphs" % (len(a), len(b), len(c), len(d)))


if __name__ == "__main__":
    main()
